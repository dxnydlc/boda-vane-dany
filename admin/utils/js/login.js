// INPUT TYPE DINÁMICO
// ======================================================
function getInputType(key) {
  if (isNumericColumn(key)) return "number";
  if (isDateColumn(key))    return "datetime-local";
  if (isTimeColumn(key))    return "time";
  return "text";
}

