function abrirTab(id) {
  const tabId = `tab-${id}`;
  const tabContentId = `tab-content-${id}`;

  if (document.getElementById(tabId)) {
    new bootstrap.Tab(document.getElementById(tabId)).show();
    return;
  }

  const item = dataJson.find(x => x.id === id);
  const chip = `<span class="badge ${estadoColors[item.Estado]} chip-glow">${item.Estado}</span>`;

  const tabHtml = `
    <li class="nav-item" id="li-${tabId}" style="border-left: 1px silver solid;border-bottom: 1px silver solid;" >
      <button class="nav-link d-flex align-items-center gap-2"
              id="${tabId}" data-bs-toggle="tab"
              data-bs-target="#${tabContentId}">
        ${id} ${chip}
        <span class="badge bg-dangerxxx " onclick="cerrarTab(event,'${tabId}','${tabContentId}')">✖</span>
      </button>
    </li>`;

  document.getElementById("editorTabs").insertAdjacentHTML("beforeend", tabHtml);

  const formHtml = generarFormulario(item);

  const contentHtml = `
    <div class="tab-pane fade" id="${tabContentId}">
      ${formHtml}
    </div>`;

  document.getElementById("editorTabsContent").insertAdjacentHTML("beforeend", contentHtml);

  new bootstrap.Tab(document.getElementById(tabId)).show();
}
