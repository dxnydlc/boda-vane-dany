function renderMesas() {
    const $contenedor = $('#contenedor-mesas');
    $contenedor.empty();

    $.each(mesas, function(index, mesa) {
        const colorMesa = mesa.color || getRandomColor();
        mesa.color = colorMesa; 

        const $divMesa = $('<div>', {
            class: 'mesa',
            css: { backgroundColor: colorMesa }
        });

        $divMesa.on('dragover', function(e) {
            e.preventDefault();
            $(this).addClass('dragover');
        }).on('dragleave', function() {
            $(this).removeClass('dragover');
        }).on('drop', function(e) {
            e.preventDefault();
            $(this).removeClass('dragover');
            const invitadoId = e.originalEvent.dataTransfer.getData('text/plain');
            asignarAMesa(invitadoId, mesa.id);
        });

        let htmlInvitados = '';
        $.each(mesa.invitados, function(i, inv) {
            // Aquí también mostramos el icono del estado dentro de la mesa
            htmlInvitados += `
                <div class="guest-in-table">
                    <div>
                        <img src="${inv.Foto}"> 
                        <span>${inv.Nombre}</span> ${getIconoEstado(inv.Estado)}
                    </div>
                    <button class="btn-remove" data-invitado-id="${inv.id}" data-mesa-id="${mesa.id}">Quitar</button>
                </div>
            `;
        });

        $divMesa.html(`
            <div class="mesa-header">
                <span>${mesa.Nombre}</span>
                <input type="color" class="color-picker" data-mesa-id="${mesa.id}" value="${colorMesa}" title="Cambiar color">
                <span>${mesa.invitados.length} invitados</span>
            </div>
            <div class="mesa-body">
                ${htmlInvitados}
            </div>
        `);

        $contenedor.append($divMesa);
    });
    
    renderResumen();
}
