function asignarAMesa(invitadoId, mesaId) {
    const invitado = invitados.find(i => String(i.id) === String(invitadoId));
    const mesa = mesas.find(m => String(m.id) === String(mesaId));
    
    if (invitado && mesa && !mesa.invitados.find(i => String(i.id) === String(invitadoId))) {
        mesa.invitados.push(invitado);
        // Llamada al backend | invitadoId | mesaId
        const obtenerCantidad = (IdMesa) => mesas.find(m => String(m.id) === String(IdMesa))?.invitados.length || 0;
        nroInvitados    = contarInvitadosPorMesa( mesaId );
        idMesa          = mesaId;
        idInvitado      = invitadoId;
        ejecutarDoc( 'add-invitado' );
        // Actualizar cantidad de invitados por mesa...
        ejecutarDoc( 'invitados-mesa' );
        actualizarUI();
    }
}
